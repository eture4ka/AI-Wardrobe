/** Опис користувача для промптів — саме тут анкета починає впливати на поради AI. */
function userContext(){
  const u=state.user;if(!u||!u.done)return "";
  const g=GENDERS.find(x=>x[0]===u.gender)?.[1];
  const who=[u.name,u.age&&u.age+" років",g].filter(Boolean).join(", ");
  const body=[u.height&&"зріст "+u.height+" см",u.sizeTop&&"розмір одягу "+u.sizeTop,u.sizeShoe&&"розмір взуття "+u.sizeShoe].filter(Boolean).join(", ");
  const q=QUIZ.map(x=>{
    const v=u.quiz[x.id];
    const txt=Array.isArray(v)?v.map(y=>QUIZ_LABEL[x.id+":"+y]).join(", "):(v?QUIZ_LABEL[x.id+":"+v]:"");
    return txt?`${x.q} ${txt}`:"";
  }).filter(Boolean).join("\n");
  return `ПРО КОРИСТУВАЧА (враховуй це в порадах):
${who?"Хто: "+who+".":""}
${body?"Параметри: "+body+".":""}
${q?"Анкета стилю:\n"+q:""}
`;
}


